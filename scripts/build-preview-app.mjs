/**
 * Bundle the preview MCP App into a TypeScript string tsc can emit.
 * Run: node scripts/build-preview-app.mjs
 */
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const bundleRoot = join(root, 'scripts/preview-app');
const install = spawnSync('npm', ['install', '--ignore-scripts'], {
  cwd: bundleRoot,
  stdio: 'inherit',
  shell: process.platform === 'win32',
});
if (install.status !== 0) {
  process.exit(install.status ?? 1);
}

const require = createRequire(join(bundleRoot, 'package.json'));
const esbuild = require('esbuild');

const result = await esbuild.build({
  entryPoints: [join(root, 'src/apps/preview/main.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  write: false,
  minify: true,
  legalComments: 'none',
  nodePaths: [join(bundleRoot, 'node_modules')],
});

const js = result.outputFiles[0].text;
const html = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
</head>
<body>
<div id="root"></div>
<script>${js}</script>
</body>
</html>
`;

const source = `// Generated by scripts/build-preview-app.mjs. Do not edit.\nexport const PREVIEW_APP_HTML = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, 'src/apps/preview-html.ts'), source);
console.log(`Wrote preview app HTML (${html.length} bytes)`);
